"""Regenerate what an IDE reads of meltygui's public interface. Run after adding or moving a view:

    .venv/bin/python stubs.py           # rewrite
    .venv/bin/python stubs.py --check   # exit 1 when a file is stale (tests/test_stubs.py)

It writes three stubs and one table, from the sources alone (nothing is imported or run):

    meltygui/__init__.pyi        every name `meltygui.<name>` answers to
    meltygui/rust.pyi            every name `meltygui.rust.<name>` answers to
    meltygui/view/__init__.pyi   the modules of `meltygui.view`
    meltygui/rust.py             its `VIEWS` table, between the two marker lines

A module-level `@gui` function named `draw_<thing>` is published as `meltygui.rust.draw_<thing>`.
To publish a package's modules the way `view` is, add it to `PACKAGES` and give it the
`__getattr__` of meltygui/view/__init__.py.
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent / 'meltygui'
PACKAGES = ('view',)
BEGIN = '# stubs.py writes the lines down to `# end`\n'
END = '# end\n'
HEADER = '# Generated by stubs.py; edit that, then run it.\n'
# names meltygui.__getattr__ answers by hand
SPECIAL = ('import meltygui_imgui\nimgui = meltygui_imgui',
           'from meltygui.core.runtime.toggles import Toggles as _Toggles\ntoggles = _Toggles',
           'from meltygui.core.windowing import window_api as window_api')


def gui_views():
    """`draw_*` name -> module, for every module-level function under `@gui`."""
    from meltygui.core.runtime.public_exports import _module_statements, _sources
    views = {}
    for path in _sources(ROOT):
        source = path.read_text(encoding='utf-8')
        if 'gui' not in source:
            continue
        module = '.'.join(('meltygui', *path.relative_to(ROOT).with_suffix('').parts))
        for node in _module_statements(ast.parse(source, filename=str(path)).body):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) or not node.name.startswith('draw_'):
                continue
            for decorator in node.decorator_list:
                target = decorator.func if isinstance(decorator, ast.Call) else decorator
                if getattr(target, 'id', None) == 'gui' or (
                        isinstance(target, ast.Attribute) and target.attr == 'gui'
                        and getattr(target.value, 'id', None) == 'meltygui'):
                    if views.setdefault(node.name, module) != module:
                        raise RuntimeError(f'Two @gui views named {node.name!r}: {views[node.name]} and {module}')
    return dict(sorted(views.items()))


def table(tree, name):
    """The literal dict assigned to `name` at module level."""
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', None) == name:
            return ast.literal_eval(node.value)
    raise KeyError(name)


def modules(folder):
    return sorted(path.stem if path.is_file() else path.name for path in folder.iterdir()
                  if (path.suffix == '.py' and path.stem != '__init__') or (path / '__init__.py').is_file())


def imports(rows):
    """Stub lines for name -> (module, original name). A stub re-exports only `import x as x`,
    so a renamed one is imported privately and assigned."""
    return ''.join(f'from {module} import {original} as {name}\n' if name == original else
                   f'from {module} import {original} as _{original}\n{name} = _{original}\n'
                   for name, (module, original) in rows.items())


def build():
    """path -> text for every generated file."""
    from meltygui.core.runtime.public_exports import discover_render_exports
    views = gui_views()

    rust_path = ROOT / 'rust.py'
    rust = rust_path.read_text(encoding='utf-8')
    head, rest = rust.split(BEGIN)
    rust = (head + BEGIN + 'VIEWS = {\n' + ''.join(f'    {name!r}: {module!r},\n' for name, module in views.items())
            + '}\n' + END + rest.split(END, 1)[1])
    core = table(ast.parse(rust), 'CORE')

    init = ast.parse((ROOT / '__init__.py').read_text(encoding='utf-8'))
    names = {alias.asname or alias.name: (node.module, alias.name) for node in init.body
             if isinstance(node, ast.ImportFrom) and node.module.startswith('meltygui') for alias in node.names}
    names |= table(init, '_LAZY_EXPORTS')
    taken = set(names) | set(modules(ROOT)) | {'imgui', 'toggles', 'window_api'}
    render = {name: spec for name, spec in sorted(discover_render_exports(ROOT).items())
              if name not in taken and not name.startswith('_')}

    files = {
        rust_path: rust,
        ROOT / 'rust.pyi': HEADER + imports({name: (module, name) for name, module in (core | views).items()}),
        ROOT / '__init__.pyi': (HEADER + '\n'.join(SPECIAL) + '\n'
                                + ''.join(f'from . import {name} as {name}\n' for name in modules(ROOT))
                                + imports(names) + '\n# @render_func views\n' + imports(render)),
    }
    for package in PACKAGES:
        files[ROOT / package / '__init__.pyi'] = HEADER + ''.join(
            f'from . import {name} as {name}\n' for name in modules(ROOT / package))
    return files


def stale():
    return [path for path, text in build().items() if not path.is_file() or path.read_text(encoding='utf-8') != text]


if __name__ == '__main__':
    changed = stale()
    if '--check' not in sys.argv:
        files = build()
        for path in changed:
            path.write_text(files[path], encoding='utf-8')
    for path in changed:
        print(('stale ' if '--check' in sys.argv else 'wrote ') + str(path.relative_to(ROOT.parent)))
    sys.exit(bool(changed) and '--check' in sys.argv)
