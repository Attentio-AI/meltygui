"""Regenerate what an IDE reads of meltygui's public interface. Run after adding or moving a view:

    .venv/bin/python stubs.py           # rewrite
    .venv/bin/python stubs.py --check   # exit 1 when a file is stale (tests/test_stubs.py)

It writes three stubs and one table, from the sources alone (nothing is imported or run):

    meltygui/__init__.pyi        every name `meltygui.<name>` answers to
    meltygui/rust.pyi            every name `meltygui.rust.<name>` answers to
    meltygui/view/__init__.pyi   the modules of `meltygui.view`
    meltygui/rust.py             its `VIEWS` table, between the two marker lines

A module-level `@gui` function named `draw_<thing>` is published as `meltygui.rust.draw_<thing>`.
rust.pyi declares each one with the signature a caller sees (`signature`): the view's own parameters,
then the names every `@gui` call takes for the framework (`FRAMEWORK`).
To publish a package's modules the way `view` is, add it to `PACKAGES` and give it the
`__getattr__` of meltygui/view/__init__.py.
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent / 'meltygui'
PACKAGES = ('view',)
BEGIN = '# stubs.py writes the lines down to `# end`\n'
END = '# end\n'
HEADER = '# Generated by stubs.py; edit that, then run it.\n'
# names meltygui.__getattr__ answers by hand
SPECIAL = ('import meltygui_imgui\nimgui = meltygui_imgui',
           'from meltygui.core.runtime.toggles import Toggles as _Toggles\ntoggles = _Toggles',
           'from meltygui.core.windowing import window_api as window_api')

# Lever: what any `@gui` call takes for the framework, name -> type, in the order the IDE lists them.
# The rest of `FILLED` (gui_prototype.py) is `INJECTED` into a body or `REJECTED` on a call; a name
# added there goes in one of these three (tests/test_stubs.py holds them together).
FRAMEWORK = {
    'name': 'str', 'key': 'str | int | tuple | None',
    'left': 'float | None', 'top': 'float | None', 'width': 'float | None', 'height': 'float | None',
    'min_width': 'float', 'max_width': 'float', 'min_height': 'float', 'max_height': 'float',
    'initial': 'dict', 'popup': 'bool', 'melty_window': 'bool', 'movable': 'bool', 'resizable': 'bool',
    'scroll': 'bool', 'scroll_offset': 'tuple[float, float]', 'content_offset': 'tuple[float, float]',
    'tint': 'tuple', 'return_extras': 'bool',
}
INJECTED = ('draw_state', 'cache', 'event', 'view_events', 'unique', 'depth', 'canvas')
REJECTED = ('glfw_window', 'window_pos')


def gui_views():
    """`draw_*` name -> module, for every module-level function under `@gui`."""
    from meltygui.core.runtime.public_exports import _module_statements, _sources
    views = {}
    for path in _sources(ROOT):
        source = path.read_text(encoding='utf-8')
        if 'gui' not in source:
            continue
        module = '.'.join(('meltygui', *path.relative_to(ROOT).with_suffix('').parts))
        for node in _module_statements(ast.parse(source, filename=str(path)).body):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) or not node.name.startswith('draw_'):
                continue
            for decorator in node.decorator_list:
                target = decorator.func if isinstance(decorator, ast.Call) else decorator
                if getattr(target, 'id', None) == 'gui' or (
                        isinstance(target, ast.Attribute) and target.attr == 'gui'
                        and getattr(target.value, 'id', None) == 'meltygui'):
                    if views.setdefault(node.name, module) != module:
                        raise RuntimeError(f'Two @gui views named {node.name!r}: {views[node.name]} and {module}')
    return dict(sorted(views.items()))


def literal(node, constants=()):
    """A default as the IDE shows it: the source of a literal (a module constant's too), `...` for
    anything computed."""
    node = constants[node.id] if isinstance(node, ast.Name) and node.id in constants else node
    try:
        ast.literal_eval(node)
    except ValueError:
        return '...'
    return ast.unparse(node)


def signature(module, name, needs):
    """The stub `def` of a view as a caller sees it. Every parameter is optional (`@gui` resolves
    the ones not passed). The view's own come first, by position up to the first name the framework
    owns; then `FRAMEWORK`, by name. `needs` collects name -> (module, original) for the annotations."""
    tree = ast.parse((ROOT.parent / (module.replace('.', '/') + '.py')).read_text(encoding='utf-8'))
    node = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == name)
    origin = {}                     # every module-level name -> where a stub imports it from
    constants = {target.id: statement.value for statement in tree.body if isinstance(statement, ast.Assign)
                 for target in statement.targets if isinstance(target, ast.Name)}
    for statement in tree.body:
        if isinstance(statement, ast.ImportFrom):
            origin |= {alias.asname or alias.name: (statement.module, alias.name) for alias in statement.names}
        elif isinstance(statement, ast.Import):
            origin |= {alias.asname or alias.name.split('.')[0]: (None, alias.name) for alias in statement.names}
        elif isinstance(statement, (ast.ClassDef, ast.Assign)):
            origin |= {target: (module, target) for target in ([statement.name] if isinstance(statement, ast.ClassDef)
                       else [getattr(target, 'id', None) for target in statement.targets])}

    def annotated(parameter):
        annotation = parameter.annotation
        if annotation is None:
            return ''
        text = ast.unparse(annotation)
        if text == 'type(None)':
            return ': None'
        for used in ast.walk(annotation):
            if isinstance(used, ast.Name) and used.id in origin:
                if needs.setdefault(used.id, origin[used.id]) != origin[used.id]:
                    raise RuntimeError(f'{name}: {used.id!r} is {origin[used.id]} here and {needs[used.id]} in another view')
        return ': ' + text

    arguments = node.args.args
    defaults = [None] * (len(arguments) - len(node.args.defaults)) + node.args.defaults
    positional, named = [], []
    target = positional
    for parameter, default in zip(arguments, defaults):
        if parameter.arg in FRAMEWORK or parameter.arg in INJECTED:
            target = named          # a value by position cannot skip it: the rest go by name
            continue
        hint = annotated(parameter)
        target.append(f'{parameter.arg}{hint}{" = " if hint else "="}{"..." if default is None else literal(default, constants)}')
    named += [f'{parameter}: {kind} = ...' for parameter, kind in FRAMEWORK.items()]
    rest = [f'**{node.args.kwarg.arg}'] if node.args.kwarg else []
    doc = ast.get_docstring(node)
    body = ' ...' if doc is None else '\n    """' + doc.replace('\n', '\n    ').replace('\\', '\\\\') + '"""'
    return f'def {name}({", ".join([*positional, "*", *named, *rest])}) -> tuple:{body}\n'


def table(tree, name):
    """The literal dict assigned to `name` at module level."""
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', None) == name:
            return ast.literal_eval(node.value)
    raise KeyError(name)


def modules(folder):
    return sorted(path.stem if path.is_file() else path.name for path in folder.iterdir()
                  if (path.suffix == '.py' and path.stem != '__init__') or (path / '__init__.py').is_file())


def imports(rows):
    """Stub lines for name -> (module, original name). A stub re-exports only `import x as x`,
    so a renamed one is imported privately and assigned."""
    return ''.join(f'from {module} import {original} as {name}\n' if name == original else
                   f'from {module} import {original} as _{original}\n{name} = _{original}\n'
                   for name, (module, original) in rows.items())


def rust_stub(core, views):
    """rust.pyi: the views (and `CORE`'s `draw_*` functions) as signatures, the rest of `CORE` re-exported."""
    needs = {}
    drawn = {name: module for name, module in (core | views).items() if name.startswith('draw_')}
    defs = [signature(module, name, needs) for name, module in drawn.items()]
    plain = ''.join(f'import {original}\n' if module is None else f'from {module} import {original}\n'
                    if name == original else f'from {module} import {original} as {name}\n'
                    for name, (module, original) in sorted(needs.items()))
    return (HEADER + plain + imports({name: (module, name) for name, module in core.items() if name not in drawn})
            + '\n\n' + '\n\n'.join(defs))


def build():
    """path -> text for every generated file."""
    from meltygui.core.runtime.public_exports import discover_render_exports
    views = gui_views()

    rust_path = ROOT / 'rust.py'
    rust = rust_path.read_text(encoding='utf-8')
    head, rest = rust.split(BEGIN)
    rust = (head + BEGIN + 'VIEWS = {\n' + ''.join(f'    {name!r}: {module!r},\n' for name, module in views.items())
            + '}\n' + END + rest.split(END, 1)[1])
    core = table(ast.parse(rust), 'CORE')

    init = ast.parse((ROOT / '__init__.py').read_text(encoding='utf-8'))
    names = {alias.asname or alias.name: (node.module, alias.name) for node in init.body
             if isinstance(node, ast.ImportFrom) and node.module.startswith('meltygui') for alias in node.names}
    names |= table(init, '_LAZY_EXPORTS')
    taken = set(names) | set(modules(ROOT)) | {'imgui', 'toggles', 'window_api'}
    render = {name: spec for name, spec in sorted(discover_render_exports(ROOT).items())
              if name not in taken and not name.startswith('_')}

    files = {
        rust_path: rust,
        ROOT / 'rust.pyi': rust_stub(core, views),
        ROOT / '__init__.pyi': (HEADER + '\n'.join(SPECIAL) + '\n'
                                + ''.join(f'from . import {name} as {name}\n' for name in modules(ROOT))
                                + imports(names) + '\n# @render_func views\n' + imports(render)),
    }
    for package in PACKAGES:
        files[ROOT / package / '__init__.pyi'] = HEADER + ''.join(
            f'from . import {name} as {name}\n' for name in modules(ROOT / package))
    return files


def stale():
    return [path for path, text in build().items() if not path.is_file() or path.read_text(encoding='utf-8') != text]


if __name__ == '__main__':
    changed = stale()
    if '--check' not in sys.argv:
        files = build()
        for path in changed:
            path.write_text(files[path], encoding='utf-8')
    for path in changed:
        print(('stale ' if '--check' in sys.argv else 'wrote ') + str(path.relative_to(ROOT.parent)))
    sys.exit(bool(changed) and '--check' in sys.argv)
