def test_deep_layout_chain_is_not_mistaken_for_feedback_cycle():
    cache = RetainedGui(graphics=False)
    extent, calls, ids = [10], Counter(), {}

    def make(level, child):
        @cache.gui(width=40, height=None)
        def view(input_value: object, draw_state=None, cache=None):
            ids[level] = cache.current
            calls[level] += 1
            draw_state.height = child(None, return_extras=True)[2].height + 1 if child else extent[0]
            return False, input_value
        return view

    root = None
    for level in range(80):
        root = make(level, root)
    try:
        root(None)
        extent[0] = 25
        cache.invalidate_id(ids[0])
        cache.flush()
        assert cache.graph.info(ids[79])['rect'][3] == 104
        assert set(calls.values()) == {2}
    finally:
        cache.close()


