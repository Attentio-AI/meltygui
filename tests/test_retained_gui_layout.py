def test_failed_measurement_preserves_previous_geometry_and_retries(graphics):
    cache = RetainedGui()
    mode, ids = [10], {}

    @cache.gui(width=40, height=None)
    def view(input_value: object, cache=None):
        ids['view'] = cache.current
        imgui.dummy(40, abs(mode[0]))
        if mode[0] < 0:
            raise ValueError('body failed')
        return False, input_value

    try:
        view(None)
        texture = cache.gpu.texture(ids['view'])
        old = raster(cache, ids['view'])
        mode[0] = -60
        cache.invalidate_id(ids['view'])
        with pytest.raises(ValueError, match='body failed'):
            cache.flush()
        assert cache.graph.info(ids['view'])['rect'][3] == 10
        np.testing.assert_array_equal(raster(cache, ids['view']), old)
        mode[0] = 60
        cache.flush()
        assert cache.graph.info(ids['view'])['rect'][3] == 60
        assert cache.gpu.texture(ids['view']) == texture
    finally:
        cache.close()


def test_result_replay_and_resize_settle_together_once(graphics):
    cache = RetainedGui()
    model, ids, edits, calls = {'value': 1}, {}, [], Counter()

    @cache.gui(width=40, height=None)
    def number(input_value: int, cache=None, view_events=None):
        calls['number'] += 1
        ids['number'] = cache.current
        value = input_value + int(view_events.get('increment', False))
        imgui.dummy(40, value * 15)
        return value != input_value, value

    @cache.gui(width=60, height=None)
    def owner(input_value: dict, cache=None):
        ids['owner'] = cache.current
        changed, value = number(input_value['value'])
        if changed:
            edits.append(value)
        input_value['value'] = value
        return changed, input_value

    try:
        owner(model)
        cache.send(ids['number'], 'increment')
        cache.flush()
        assert model['value'] == 2 and edits == [2]
        assert cache.graph.info(ids['owner'])['rect'][3] == 30
        assert calls['number'] == 2
        assert owner(model)[0] is True
        assert owner(model)[0] is False
        assert edits == [2] and calls['number'] == 2
    finally:
        cache.close()


def test_keyed_reorder_insert_remove_and_shared_aliases(graphics):
    cache = RetainedGui()
    order, model, ids, calls = ['a', 'b', 'c'], {'height': 12}, {}, Counter()

    @cache.gui(width=40, height=None)
    def item(input_value: dict, name='', cache=None):
        ids[name] = cache.current
        calls[name] += 1
        imgui.get_window_draw_list().add_rect_filled(0, 0, 40, input_value['height'],
                                                   {'a': 0xFF0000FF, 'b': 0xFF00FF00,
                                                    'c': 0xFFFF0000, 'd': 0xFFFFFFFF}[name])
        imgui.dummy(40, input_value['height'])
        return False, input_value

    @cache.gui(width=50, height=None)
    def root(input_value: object, cache=None):
        ids['root'] = cache.current
        for name in order:
            item(model, key=name, name=name)
        return False, input_value

    try:
        root(None)
        original = ids.copy()
        order[:] = ['c', 'a', 'd']
        cache.invalidate_id(ids['root'])
        cache.flush()
        assert ids['a'] == original['a'] and ids['c'] == original['c']
        assert original['b'] not in cache.graph.nodes()
        assert calls == Counter(a=1, b=1, c=1, d=1)
        assert [cache.graph.info(ids[k])['rect'][1] for k in order] == [0, 16, 32]
        model['height'] = 25
        assert cache.invalidate(model) == 3
        cache.flush()
        assert calls == Counter(a=2, b=1, c=2, d=2)
        assert [cache.graph.info(ids[k])['rect'][1] for k in order] == [0, 29, 58]
        assert cache.graph.info(ids['root'])['rect'][3] == 83
        result = raster(cache, ids['root'])
        assert tuple(result[-8, 8]) == (0, 0, 255, 255)
        assert tuple(result[-37, 8]) == (255, 0, 0, 255)
        assert tuple(result[-66, 8]) == (255, 255, 255, 255)
    finally:
        cache.close()


