def test_new_width_does_not_get_lost_while_returned_edit_is_pending():
    cache = RetainedGui(graphics=False)
    ids, widths = [], []

    @cache.gui(height=None)
    def view(input_value: int, draw_state=None, cache=None, view_events=None):
        ids[:] = [cache.current]
        widths.append(draw_state.width)
        value = input_value + int(view_events.get('increment', False))
        draw_state.height = value * 10
        return value != input_value, value

    try:
        view(1, width=300)
        cache.send(ids[0], 'increment')
        cache.flush()
        # The caller still echoes the old scalar while also changing constraints.
        assert view(1, width=90) == (True, 2)
        assert widths == [300, 300, 90]
        assert cache.graph.info(ids[0])['rect'][2:] == (90, 20)
        assert view(2, width=90) == (False, 2)
        assert widths == [300, 300, 90]
    finally:
        cache.close()


