def test_seeded_layout_transitions_match_fresh_render_and_retire_resources(graphics):
    import random
    rng = random.Random(42)
    model = {'height': 12., 'show': True}
    cache, root, _, ids = scene(model)
    try:
        for step in range(80):
            previous_show = model['show']
            model.update(height=float(rng.randrange(0, 130)), show=rng.random() > .2,
                         color=rng.choice([0xFF0000FF, 0xFF00FF00, 0xFFFFFF00]))
            if previous_show != model['show']:
                cache.invalidate_id(ids['owner'])
            if ids.get('leaf') in cache.records:
                cache.invalidate_id(ids['leaf'])
            cache.flush()
            fresh, _, _, fresh_ids = scene(model)
            try:
                np.testing.assert_array_equal(raster(cache, ids['root']), raster(fresh, fresh_ids['root']),
                                              err_msg=f'transition {step}: {model}')
                assert len(cache.records) == len(fresh.records)
                assert set(cache.contexts) == set(cache.records) == set(cache.graph.nodes())
            finally:
                fresh.close()
            calls = {node: cache.graph.info(node)['executions'] for node in cache.graph.nodes()}
            stats = cache.gpu.stats()
            root(None)
            cache.flush()
            assert {node: cache.graph.info(node)['executions'] for node in cache.graph.nodes()} == calls
            assert cache.gpu.stats() == stats
    finally:
        cache.close()
