def scene(model, *, fixed_parent=False, horizontal=False):
    cache = RetainedGui()
    calls, ids = Counter(), {}

    def mark(name):
        calls[name] += 1
        ids[name] = cache.current

    @cache.gui(width=None, height=None)
    def leaf(input_value: object, draw_state=None, cache=None):
        mark('leaf')
        height = model['height']
        color = model.get('color', 0xFF0000FF)
        imgui.get_window_draw_list().add_rect_filled(0, 0, draw_state.width, height, color)
        imgui.dummy(draw_state.width, height)
        cache.region('leaf', (0, 0, draw_state.width, height))
        return False, input_value

    @cache.gui(width=20, height=13)
    def sibling(input_value: object, cache=None):
        mark('sibling')
        imgui.get_window_draw_list().add_rect_filled(0, 0, 20, 13, 0xFF00FF00)
        cache.region('sibling', (0, 0, 20, 13))
        return False, input_value

    @cache.gui(width=None, height=70 if fixed_parent else None)
    def owner(input_value: object):
        mark('owner')
        if model.get('show', True):
            leaf(None, width=35 if horizontal else None)
        if horizontal:
            imgui.same_line()
        sibling(None)
        return False, input_value

    @cache.gui(width=130, height=180)
    def root(input_value: object):
        mark('root')
        imgui.set_cursor_screen_pos((7, 9))
        owner(None)
        imgui.dummy(1, 3)
        # Deliberately generated by the ancestor: its location depends on height.
        x, y = imgui.get_cursor_screen_pos()
        imgui.get_window_draw_list().add_rect_filled(x, y, x + 100, y + 5, 0xFFFF0000)
        return False, input_value

    root(None)
    return cache, root, calls, ids


def raster(cache, node):
    _, _, w, h = cache.graph.info(node)['rect']
    return pixels(cache.gpu.texture(node), int(w), max(1, int(h)))


@pytest.mark.parametrize('fixed_parent', [False, True])
@pytest.mark.parametrize('horizontal', [False, True])
def test_grow_shrink_zero_and_fractional_match_full_render(graphics, fixed_parent, horizontal):
    model = {'height': 18.25}
    cache, root, calls, ids = scene(model, fixed_parent=fixed_parent, horizontal=horizontal)
    original_ids = ids.copy()
    texture = cache.gpu.texture(ids['leaf'])
    try:
        for height in [80.75, 2., 0., 0., 37.5, 9., 115., 4.]:
            before = calls.copy()
            old_owner_h = cache.graph.info(ids['owner'])['rect'][3]
            old_leaf_h = cache.graph.info(ids['leaf'])['rect'][3]
            model['height'] = height
            cache.invalidate_id(ids['leaf'])
            cache.flush()
            assert ids == original_ids
            assert cache.gpu.texture(ids['leaf']) == texture
            # ImGui snaps item extents to pixels; use its measured layout extent.
            assert cache.graph.info(ids['leaf'])['rect'][3] == math.floor(height)
            assert calls['leaf'] == before['leaf'] + 1
            assert calls['sibling'] == before['sibling']
            assert calls['owner'] == before['owner'] + int(old_leaf_h != math.floor(height))
            owner_h = cache.graph.info(ids['owner'])['rect'][3]
            assert calls['root'] == before['root'] + int(owner_h != old_owner_h)
            fresh, _, _, fresh_ids = scene(model, fixed_parent=fixed_parent, horizontal=horizontal)
            try:
                for name in ids:
                    assert cache.graph.info(ids[name])['rect'] == fresh.graph.info(fresh_ids[name])['rect']
                    np.testing.assert_array_equal(raster(cache, ids[name]), raster(fresh, fresh_ids[name]))
            finally:
                fresh.close()
            stats = cache.gpu.stats()
            settled = calls.copy()
            root(None)
            cache.flush()
            assert calls == settled and cache.gpu.stats() == stats
    finally:
        cache.close()


