def test_owner_removal_wins_over_queued_resize_and_frees_texture(graphics):
    model = {'height': 20.}
    cache, _, calls, ids = scene(model)
    try:
        leaf_id = ids['leaf']
        before = calls.copy()
        model.update(height=70., show=False)
        cache.invalidate_id(leaf_id)
        cache.invalidate_id(ids['owner'])
        cache.flush()
        assert calls['leaf'] == before['leaf']
        assert leaf_id not in cache.graph.nodes()
        assert leaf_id not in cache.contexts and leaf_id not in cache.records
        assert cache.gpu.texture(leaf_id) is None
        fresh, _, _, fresh_ids = scene(model)
        try:
            np.testing.assert_array_equal(raster(cache, ids['root']), raster(fresh, fresh_ids['root']))
        finally:
            fresh.close()
    finally:
        cache.close()


def test_width_change_rewraps_text_and_moves_cached_sibling(graphics):
    cache = RetainedGui()
    calls, ids = Counter(), {}

    @cache.gui(width=None, height=None)
    def paragraph(input_value: str, draw_state=None, cache=None):
        calls['paragraph'] += 1
        ids['paragraph'] = cache.current
        imgui.push_text_wrap_pos(draw_state.width)
        imgui.text_unformatted(input_value)
        imgui.pop_text_wrap_pos()
        return False, input_value

    @cache.gui(width=20, height=12)
    def tail(input_value: object, cache=None):
        calls['tail'] += 1
        ids['tail'] = cache.current
        return False, input_value

    @cache.gui(height=None)
    def root(input_value: str, cache=None):
        ids['root'] = cache.current
        paragraph(input_value)
        tail(None)
        return False, input_value

    value = 'Variable width text must wrap and move the next cached item without rerunning that item.'
    try:
        sizes = []
        for width in (300, 90, 300):
            root(value, width=width)
            cache.flush()
            sizes.append(cache.graph.info(ids['root'])['rect'][3])
            assert cache.graph.info(ids['paragraph'])['rect'][2] == width
            py = cache.graph.info(ids['paragraph'])['rect'][3]
            assert cache.graph.info(ids['tail'])['rect'][1] == py + 4
        assert sizes[1] > sizes[0] == sizes[2]
        assert calls == Counter(paragraph=3, tail=1)
    finally:
        cache.close()


